// Local browser acceptance against real APIs. Creates a fresh synthetic account.
// No credentials, cookies or private browser profile are saved.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
const { randomUUID } = require('node:crypto');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const base = process.env.PREVIEW_URL || 'http://127.0.0.1:5173';
assert.ok(['127.0.0.1', 'localhost'].includes(new URL(base).hostname), 'Local acceptance only');
const output = path.resolve(process.env.QA_TEMPLATE_OUTPUT || path.join(__dirname, '../../artifacts/template-browser'));
const checks = [];
async function main() {
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : {}) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const page = await context.newPage();
  page.setDefaultTimeout(15000);
  const runtimeErrors = [];
  const aiWrites = [];
  page.on('pageerror', error => runtimeErrors.push(error.message));
  page.on('request', request => { if (request.method() !== 'GET' && /\/api\/.*(ai-tasks|analysis-sessions|image-tasks)/.test(request.url())) aiWrites.push(request.url()); });
  const record = text => { checks.push(text); console.log('PASS', text); };
  const visible = locator => locator.waitFor({ state: 'visible' });
  const screenshot = name => page.screenshot({ path: path.join(output, name), fullPage: true });
  async function noOverflow(label) {
    const sizes = await page.evaluate(() => ({ client: document.documentElement.clientWidth, scroll: document.documentElement.scrollWidth }));
    assert.equal(sizes.client, sizes.scroll, label); record(label);
  }
  try {
    await page.goto(base + '/auth?mode=register&next=%2Fapp%2Ftemplates');
    await page.getByLabel('邮箱', { exact: true }).fill(`templates-${randomUUID()}@example.com`);
    const password = 'Qa1!' + randomUUID();
    await page.getByLabel('密码', { exact: true }).fill(password);
    await page.getByLabel('确认密码', { exact: true }).fill(password);
    await page.getByRole('button', { name: '注册并进入工作空间' }).click();
    await visible(page.getByRole('heading', { name: '模板中心', exact: true }));
    await visible(page.getByRole('article', { name: '校园调查统计口径', exact: true }));
    record('新合成账户通过真实注册进入模板中心，读取三个内置模板');
    await page.getByLabel('模板来源', { exact: true }).selectOption('我的模板');
    await visible(page.getByRole('heading', { name: '还没有自己的模板' }));
    record('我的模板空状态');
    await page.getByRole('button', { name: '添加模板', exact: true }).first().click();
    let dialog = page.getByRole('dialog');
    await dialog.getByLabel('模板名称', { exact: true }).fill('本机合成验收模板');
    await dialog.getByRole('button', { name: '保存模板', exact: true }).click();
    await visible(dialog.getByRole('alert'));
    record('只有名称不能保存空模板');
    await dialog.getByLabel('用途分类', { exact: true }).selectOption('反馈统计');
    await dialog.getByLabel('用途说明（选填）', { exact: true }).fill('本机验收：可复用的活动反馈草稿，不含真实个人资料。');
    const draft = '纳入范围：本次活动有效反馈。\n分子定义：【按本次资料确认】\n空值策略：【待确认】';
    await dialog.getByLabel('规则草稿', { exact: true }).fill(draft);
    await dialog.getByLabel('报告提纲', { exact: true }).fill('一、资料来源\n二、统计口径\n三、后台结果与证据');
    await dialog.getByRole('button', { name: '保存模板', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    await visible(page.getByText('模板已保存到你的账户，可以立即使用。', { exact: true }));
    await page.reload();
    let card = page.getByRole('article', { name: '本机合成验收模板', exact: true });
    await visible(card);
    record('添加模板经真实API保存，刷新后仍可读取');
    await card.getByRole('button', { name: '编辑模板' }).click();
    await dialog.getByLabel('模板名称', { exact: true }).fill('本机合成验收模板 · 已编辑');
    await dialog.getByRole('button', { name: '保存模板', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    card = page.getByRole('article', { name: '本机合成验收模板 · 已编辑', exact: true });
    await visible(card.getByText('我的模板 · v2', { exact: true }));
    record('编辑模板成功并显示v2');
    await card.getByRole('button', { name: '使用模板', exact: true }).click();
    await dialog.getByLabel('新项目名称', { exact: true }).fill('模板套用验收项目');
    await dialog.getByRole('button', { name: '创建项目并使用' }).click();
    await page.waitForURL(/\/app\/projects\/[^/]+\/materials$/);
    const projectUrl = page.url();
    const panel = page.getByRole('region', { name: '项目模板草稿' });
    await visible(panel.getByRole('heading', { name: '从「本机合成验收模板 · 已编辑」开始' }));
    await panel.locator('summary').click();
    assert.equal(await panel.locator('.template-content p').first().innerText(), draft);
    record('使用自建模板创建真实项目，规则和报告提纲快照显示正确');
    await screenshot('template-project-1440.png');
    await panel.getByRole('button', { name: '完善并保存规则说明' }).click();
    dialog = page.getByRole('dialog');
    assert.equal(await dialog.locator('textarea').inputValue(), draft);
    await dialog.locator('textarea').fill('本机合成验收规则：纳入本次活动有效反馈；所有口径仍需逐项确认。');
    await dialog.getByRole('button', { name: '保存规则文本' }).click();
    await dialog.waitFor({ state: 'hidden' });
    await visible(page.getByText('本机合成验收模板 · 已编辑 · 规则说明', { exact: true }).first());
    record('模板草稿能进入现有规则文本表单并真实保存；不自动确认规则');
    await page.goto(base + '/app/templates');
    card = page.getByRole('article', { name: '本机合成验收模板 · 已编辑', exact: true });
    await card.getByRole('button', { name: '编辑模板' }).click();
    await page.getByRole('dialog').getByLabel('规则草稿', { exact: true }).fill('后续模板版本，不应覆盖已经套用的项目。');
    await page.getByRole('dialog').getByRole('button', { name: '保存模板', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    await page.goto(projectUrl);
    await panel.locator('summary').click();
    assert.equal(await panel.locator('.template-content p').first().innerText(), draft);
    record('编辑原模板后，已创建项目继续保留旧版草稿');
    await page.goto(base + '/app/templates');
    await page.getByRole('article', { name: '校园调查统计口径', exact: true }).getByRole('button', { name: '另存为我的模板' }).click();
    await page.getByRole('dialog').getByLabel('模板名称', { exact: true }).fill('我的校园调查模板');
    await page.getByRole('dialog').getByRole('button', { name: '保存模板', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    await visible(page.getByRole('article', { name: '我的校园调查模板', exact: true }));
    record('内置模板可另存为个人模板');
    await page.getByLabel('搜索模板', { exact: true }).fill('不存在的合成名称');
    await visible(page.getByRole('heading', { name: '没有找到匹配的模板' }));
    await page.getByLabel('搜索模板', { exact: true }).fill('');
    await page.getByLabel('模板来源', { exact: true }).selectOption('全部');
    record('搜索与来源筛选及无匹配状态');
    await page.route('**/api/templates', route => route.request().method() === 'GET' ? route.abort('failed') : route.continue());
    await page.getByRole('button', { name: '刷新列表', exact: true }).click();
    await visible(page.getByRole('alert'));
    await page.unroute('**/api/templates');
    await page.getByRole('button', { name: '刷新列表', exact: true }).click();
    await page.getByRole('alert').waitFor({ state: 'hidden' });
    record('请求失败可见错误提示，刷新成功后错误清除');
    for (const width of [1440, 390, 320]) {
      await page.setViewportSize({ width, height: width === 1440 ? 1000 : 844 });
      await noOverflow(`模板列表 ${width}px 无页面横向溢出`);
      await screenshot(`templates-${width}.png`);
      await page.getByRole('button', { name: '添加模板', exact: true }).click();
      await page.getByRole('dialog').getByLabel('模板名称', { exact: true }).fill('长内容边界验收');
      await page.getByRole('dialog').getByLabel('规则草稿', { exact: true }).fill('这是一段合成规则说明。'.repeat(200));
      const box = await page.getByRole('dialog').boundingBox();
      assert.ok(box.x >= 0 && box.x + box.width <= width && box.y >= 0 && box.height <= (width === 1440 ? 1000 : 844));
      await screenshot(`template-form-${width}.png`);
      await page.keyboard.press('Escape');
      await page.getByRole('dialog').waitFor({ state: 'hidden' });
      assert.equal(await page.evaluate(() => document.activeElement.textContent.trim()), '添加模板');
      record(`模板表单 ${width}px 在视口内，长内容可滚动，Escape关闭并回焦`);
    }
    assert.deepEqual(runtimeErrors, []); assert.deepEqual(aiWrites, []);
    record('无页面运行时异常，未发起AI请求');
    fs.writeFileSync(path.join(output, 'validation.json'), JSON.stringify({ checks, browser: browser.version(), method: 'isolated headless Chromium using installed Microsoft Edge; real local APIs; synthetic account', aiRequests: 0 }, null, 2));
  } catch (error) {
    await screenshot('failure.png').catch(() => {});
    throw error;
  } finally { await browser.close(); }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
